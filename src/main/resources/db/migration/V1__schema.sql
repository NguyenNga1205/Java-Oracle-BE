-- PostgreSQL schema, mirrors the JPA entities in vn.edu.qlsv.model.
-- Ids are BIGINT identity; flags (enabled/active) stay INTEGER 0/1 to match NumericBooleanConverter.

CREATE SEQUENCE seq_course_code START 1;
CREATE SEQUENCE seq_faculty_code START 1;
CREATE SEQUENCE seq_classroom_code START 1;

CREATE TABLE course_years (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL UNIQUE,
    name       VARCHAR(120) NOT NULL,
    start_year INTEGER      NOT NULL
);

CREATE TABLE faculties (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(30)  NOT NULL UNIQUE,
    name           VARCHAR(120) NOT NULL,
    course_year_id BIGINT       NOT NULL REFERENCES course_years (id)
);

CREATE TABLE teachers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL UNIQUE,
    full_name  VARCHAR(120) NOT NULL,
    email      VARCHAR(255),
    faculty_id BIGINT REFERENCES faculties (id)
);

CREATE TABLE classrooms (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(30)  NOT NULL UNIQUE,
    name         VARCHAR(120) NOT NULL,
    faculty_id   BIGINT       NOT NULL REFERENCES faculties (id),
    teacher_id   BIGINT REFERENCES teachers (id),
    max_students INTEGER      NOT NULL DEFAULT 50,
    CONSTRAINT ck_class_max CHECK (max_students = 50)
);

CREATE TABLE subjects (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL UNIQUE,
    name       VARCHAR(120) NOT NULL,
    faculty_id BIGINT       NOT NULL REFERENCES faculties (id)
);

CREATE TABLE students (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(30)  NOT NULL UNIQUE,
    full_name     VARCHAR(120) NOT NULL,
    date_of_birth DATE,
    gender        VARCHAR(20),
    email         VARCHAR(255),
    phone         VARCHAR(20),
    status        VARCHAR(30)  NOT NULL DEFAULT 'STUDYING',
    classroom_id  BIGINT REFERENCES classrooms (id),
    CONSTRAINT ck_student_status
        CHECK (status IN ('STUDYING', 'SUSPENDED', 'RESERVED', 'GRADUATED', 'DROPPED_OUT', 'EXPELLED')),
    CONSTRAINT uq_students_id_class UNIQUE (id, classroom_id)
);

CREATE INDEX ix_student_class ON students (classroom_id);
CREATE INDEX ix_class_faculty ON classrooms (faculty_id);
CREATE INDEX ix_class_teacher ON classrooms (teacher_id);

CREATE TABLE classroom_subjects (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT NOT NULL REFERENCES classrooms (id),
    subject_id   BIGINT NOT NULL REFERENCES subjects (id),
    teacher_id   BIGINT NOT NULL REFERENCES teachers (id),
    CONSTRAINT uq_classroom_subject UNIQUE (classroom_id, subject_id),
    CONSTRAINT uq_cls_sub_id_class UNIQUE (id, classroom_id)
);

CREATE INDEX ix_cls_subject_teacher ON classroom_subjects (teacher_id);

CREATE TABLE student_subjects (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id           BIGINT    NOT NULL,
    classroom_id         BIGINT    NOT NULL,
    classroom_subject_id BIGINT    NOT NULL,
    enrolled_at          TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT uq_student_class_subject UNIQUE (student_id, classroom_subject_id),
    CONSTRAINT fk_student_subject_student_class
        FOREIGN KEY (student_id, classroom_id) REFERENCES students (id, classroom_id),
    CONSTRAINT fk_student_subject_class_subject
        FOREIGN KEY (classroom_subject_id, classroom_id) REFERENCES classroom_subjects (id, classroom_id)
);

CREATE INDEX ix_student_subject_student ON student_subjects (student_id);
CREATE INDEX ix_student_subject_offering ON student_subjects (classroom_subject_id);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(80)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    enabled       INTEGER      NOT NULL DEFAULT 1,
    student_id    BIGINT REFERENCES students (id),
    teacher_id    BIGINT REFERENCES teachers (id),
    CONSTRAINT ck_user_role CHECK (role IN ('ADMIN', 'TEACHER', 'STUDENT')),
    CONSTRAINT ck_user_link CHECK (
        (role = 'ADMIN' AND student_id IS NULL AND teacher_id IS NULL)
        OR (role = 'TEACHER' AND student_id IS NULL AND teacher_id IS NOT NULL)
        OR (role = 'STUDENT' AND student_id IS NOT NULL AND teacher_id IS NULL))
);

CREATE UNIQUE INDEX ux_user_student ON users (student_id);
CREATE UNIQUE INDEX ux_user_teacher ON users (teacher_id);

-- DAY_OF_WEEK: 2=Monday ... 8=Sunday. START/END_MINUTE: minutes from 00:00.
CREATE TABLE weekly_schedules (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_subject_id BIGINT  NOT NULL REFERENCES classroom_subjects (id),
    day_of_week          INTEGER NOT NULL,
    start_minute         INTEGER NOT NULL,
    end_minute           INTEGER NOT NULL,
    room                 VARCHAR(100),
    effective_from       DATE    NOT NULL,
    effective_to         DATE,
    active               INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT ck_wsch_day CHECK (day_of_week BETWEEN 2 AND 8),
    CONSTRAINT ck_wsch_start CHECK (start_minute BETWEEN 0 AND 1439),
    CONSTRAINT ck_wsch_end CHECK (end_minute BETWEEN 1 AND 1440 AND end_minute > start_minute),
    CONSTRAINT ck_wsch_active CHECK (active IN (0, 1)),
    CONSTRAINT ck_wsch_effective CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CONSTRAINT uq_wsch_id_csub UNIQUE (id, classroom_subject_id)
);

CREATE INDEX ix_wsch_class_subject ON weekly_schedules (classroom_subject_id);

CREATE TABLE class_sessions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weekly_schedule_id   BIGINT,
    classroom_subject_id BIGINT      NOT NULL REFERENCES classroom_subjects (id),
    session_no           INTEGER,
    session_date         DATE        NOT NULL,
    start_minute         INTEGER     NOT NULL,
    end_minute           INTEGER     NOT NULL,
    room                 VARCHAR(100),
    status               VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    note                 VARCHAR(1000),
    CONSTRAINT fk_cses_weekly_subject
        FOREIGN KEY (weekly_schedule_id, classroom_subject_id)
        REFERENCES weekly_schedules (id, classroom_subject_id),
    CONSTRAINT ck_cses_start CHECK (start_minute BETWEEN 0 AND 1439),
    CONSTRAINT ck_cses_end CHECK (end_minute BETWEEN 1 AND 1440 AND end_minute > start_minute),
    CONSTRAINT ck_cses_status CHECK (status IN ('SCHEDULED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT uq_cses_week_date UNIQUE (weekly_schedule_id, session_date),
    CONSTRAINT uq_cses_id_csub UNIQUE (id, classroom_subject_id)
);

CREATE INDEX ix_cses_class_subject_date ON class_sessions (classroom_subject_id, session_date);
CREATE INDEX ix_cses_weekly_schedule ON class_sessions (weekly_schedule_id);

-- One row per student per session. Matches the Attendance entity (STUDENT_ID + CLASSROOM_ID),
-- not the legacy STUDENT_SUBJECT_ID layout of the Oracle 05 script.
CREATE TABLE attendance (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id           BIGINT      NOT NULL,
    classroom_subject_id BIGINT      NOT NULL,
    student_id           BIGINT      NOT NULL,
    classroom_id         BIGINT      NOT NULL,
    marked_by_teacher_id BIGINT      NOT NULL REFERENCES teachers (id),
    status               VARCHAR(20) NOT NULL,
    note                 VARCHAR(500),
    marked_at            TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT fk_att_session_subject
        FOREIGN KEY (session_id, classroom_subject_id) REFERENCES class_sessions (id, classroom_subject_id),
    CONSTRAINT fk_att_student_class
        FOREIGN KEY (student_id, classroom_id) REFERENCES students (id, classroom_id),
    CONSTRAINT fk_att_class_subject
        FOREIGN KEY (classroom_subject_id, classroom_id) REFERENCES classroom_subjects (id, classroom_id),
    CONSTRAINT ck_att_status CHECK (status IN ('PRESENT', 'ABSENT', 'LATE')),
    CONSTRAINT uq_att_session_student UNIQUE (session_id, student_id)
);

CREATE INDEX ix_att_student ON attendance (student_id);
CREATE INDEX ix_att_teacher ON attendance (marked_by_teacher_id);
